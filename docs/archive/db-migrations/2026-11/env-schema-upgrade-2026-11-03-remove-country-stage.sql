-- =====================================================================================
-- 增量升级脚本（2026-11-03）：删除 md_environment 的 country / stage
-- =====================================================================================
-- 背景：这两个字段只服务于旧页面的筛选、分组展示与编辑表单，工具解析环境时从未读取；
--   页面已同步移除，因此主表不再保留这两列。
--
-- 为什么单独一份：
--   env-schema.sql 是「全新建库」脚本，把 ALTER 混进去会让重跑建表脚本变得不安全。
--
-- 幂等性：本脚本**不是**幂等的。重复执行会报找不到列/索引的错误，说明已经升过。
--
-- 执行方式：在有 mysql 客户端的环境里 source 本文件，或执行下方等价语句。
-- 注意：删列不可逆，执行前先备份 md_environment。
-- =====================================================================================

ALTER TABLE `md_environment`
    DROP KEY `idx_country_stage`,
    DROP COLUMN `country`,
    DROP COLUMN `stage`;
