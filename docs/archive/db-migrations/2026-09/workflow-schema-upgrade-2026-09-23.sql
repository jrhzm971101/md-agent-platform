-- =====================================================================================
-- md_agent_run 补两列 —— 让「工作流节点」和「它呼出来的那条执行链路」对上
-- =====================================================================================
-- 为什么改的是既有表而不是新开一张关联表：
--   关联关系是 1:1（一次 agent 调用最多属于一个工作流节点），新开一张关联表意味着
--   每次查执行链路都要多一次 JOIN，而这两列本身加起来才 128 字节。
--   更要紧的是：加了列之后，执行链路列表可以直接按「只看某次工作流运行」筛选，
--   不需要先查关联表拿到 runId 列表再 IN 进去。
--
-- 为什么可空：绝大多数 run 不是工作流发起的（页面对话 / 企微 / 飞书 / 定时任务）。
--   NULL 的语义是「这条链路不属于任何工作流运行」，不是「属于但没记」——
--   source 列的做法与这里相反（NULL = 入口方没标注），别把两者混为一谈。
--
-- 为什么不加外键指向 md_workflow_run(run_id)：沿用本项目「观测数据不做外键」的既定风格
--   （见 trace-schema.sql 头部注释）。执行链路是可丢弃的，不应因为编排记录被清理而写不进去。
--
-- 与 workflow-schema.sql 的关系：先执行那份建 4 张新表，再执行本脚本补这两列。
-- 本脚本对已存在的库只执行一次；重复执行会因「列已存在」报错，这是刻意的
--   —— 静默忽略重复执行需要写存储过程去查 information_schema，
--      而这类一次性升级脚本的错误应当显式暴露，而不是看起来"成功"却没生效。
-- =====================================================================================

ALTER TABLE `md_agent_run`
    ADD COLUMN `workflow_run_id`   VARCHAR(64) DEFAULT NULL
        COMMENT '所属工作流运行 id（md_workflow_run.run_id）；NULL = 不是工作流发起的' AFTER `source`,
    ADD COLUMN `workflow_node_key` VARCHAR(64) DEFAULT NULL
        COMMENT '所属工作流节点 key；NULL = 不是工作流发起的' AFTER `workflow_run_id`;

-- 页面从「工作流运行详情」跳过来时，是按 (workflow_run_id, workflow_node_key) 精确定位一条链路，
-- 所以索引的两列顺序按这个查询来定；单个 workflow_run_id 的过滤（"这次编排一共呼了多少条链路"）
-- 用同一棵索引的最左前缀即可，不需要再建一个单列索引。
ALTER TABLE `md_agent_run`
    ADD KEY `idx_workflow_run` (`workflow_run_id`, `workflow_node_key`);